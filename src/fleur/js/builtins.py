from typing import TYPE_CHECKING, Final, final

from .builder import Null, Number, Undefined, _GlobalMeta

NULL: Final[Null] = Null()
UNDEFINED: Final[Undefined] = Undefined()


@final
class Math(metaclass=_GlobalMeta):
    """Provides access to JavaScript's Math object methods and properties."""

    __fleur_global_name__: Final[str] = "Math"

    if TYPE_CHECKING:
        # Static properties
        E: Number
        LN10: Number
        LOG10E: Number
        LOG2E: Number
        PI: Number
        SQRT1_2: Number
        SQRT2: Number

        # Static methods
        @staticmethod
        def abs(x: Number) -> Number: ...
        @staticmethod
        def acos(x: Number) -> Number: ...
        @staticmethod
        def acosh(x: Number) -> Number: ...
        @staticmethod
        def asin(x: Number) -> Number: ...
        @staticmethod
        def asinh(x: Number) -> Number: ...
        @staticmethod
        def atan(x: Number) -> Number: ...
        @staticmethod
        def atan2(y: Number, x: Number) -> Number: ...
        @staticmethod
        def atanh(x: Number) -> Number: ...
        @staticmethod
        def cbrt(x: Number) -> Number: ...
        @staticmethod
        def ceil(x: Number) -> Number: ...
        @staticmethod
        def clz32(x: Number) -> Number: ...
        @staticmethod
        def cos(x: Number) -> Number: ...
        @staticmethod
        def cosh(x: Number) -> Number: ...
        @staticmethod
        def exp(x: Number) -> Number: ...
        @staticmethod
        def expm1(x: Number) -> Number: ...
        @staticmethod
        def floor(x: Number) -> Number: ...
        @staticmethod
        def fround(x: Number) -> Number: ...
        @staticmethod
        def hypot(*values: Number) -> Number: ...
        @staticmethod
        def imul(x: Number, y: Number) -> Number: ...
        @staticmethod
        def log(x: Number) -> Number: ...
        @staticmethod
        def log10(x: Number) -> Number: ...
        @staticmethod
        def log1p(x: Number) -> Number: ...
        @staticmethod
        def log2(x: Number) -> Number: ...
        @staticmethod
        def max(*values: Number) -> Number: ...
        @staticmethod
        def min(*values: Number) -> Number: ...
        @staticmethod
        def pow(base: Number, exponent: Number) -> Number: ...
        @staticmethod
        def random() -> Number: ...
        @staticmethod
        def round(x: Number) -> Number: ...
        @staticmethod
        def sign(x: Number) -> Number: ...
        @staticmethod
        def sin(x: Number) -> Number: ...
        @staticmethod
        def sinh(x: Number) -> Number: ...
        @staticmethod
        def sqrt(x: Number) -> Number: ...
        @staticmethod
        def tan(x: Number) -> Number: ...
        @staticmethod
        def tanh(x: Number) -> Number: ...
        @staticmethod
        def trunc(x: Number) -> Number: ...
